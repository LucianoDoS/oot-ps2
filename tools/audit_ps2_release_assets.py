"""Refuse a public EE release that still contains ROM-derived initializers."""
import argparse
import hashlib
import json
from pathlib import Path
from ps2_release_assets import Elf, inventory


def audit(project, elf_path, generated, procedural_icon=False):
    data = elf_path.read_bytes()
    elf = Elf(data)
    linked, absent = inventory(project, elf, generated, not procedural_icon)
    records = []
    for symbol, info in linked:
        payload = data[symbol.file_offset:symbol.file_offset + symbol.size]
        records.append(dict(info, bytes=symbol.size, address=f"0x{symbol.address:08x}",
                            file_offset=symbol.file_offset, sha256=hashlib.sha256(payload).hexdigest(),
                            initialized=any(payload)))
    embedded = [item for item in records if item["initialized"]]
    return dict(schema=1, status="FAIL" if embedded else "PASS", elf_sha256=hashlib.sha256(data).hexdigest(),
                asset_symbols=len(records), asset_bytes=sum(item["bytes"] for item in records),
                nonzero_private_symbols=len(embedded), absent_version_or_optimized_arrays=absent,
                records=records, procedural_icon=procedural_icon,
                limitation="Audits declared extracted initializer arrays, microcode and private icon; does not certify copyright or license compliance of game code.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--elf", type=Path, required=True)
    parser.add_argument("--generated", type=Path, default=Path("build/PS2-ntsc12/generated"))
    parser.add_argument("--procedural-icon", action="store_true", help="Icon was generated by generate_ps2_public_icon.py")
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    result = audit(Path(__file__).resolve().parents[1], args.elf, args.generated, args.procedural_icon)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: result[key] for key in ("status", "asset_symbols", "asset_bytes", "nonzero_private_symbols")}))
    raise SystemExit(result["status"] != "PASS")


if __name__ == "__main__":
    main()
